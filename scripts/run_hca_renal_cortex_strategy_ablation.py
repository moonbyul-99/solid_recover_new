"""HCA renal cortex 训练策略消融实验一键编排脚本（单 seed）。

三种训练策略（严格消融标准，仅 seed=0，耗时控制）：

  1. aug_pt   : test 增强预训练（train+test 合并的单模态数据预训练）+ 联合训练 (pair_pretrain)
  2. scratch  : 无预训练，直接使用 train 数据集做匹配训练 (pair_scratch)
  3. train_pt : 仅使用 train 单模态数据预训练 + 联合训练 (pair_pretrain)

联合训练超参数（参考 outputs/hca_renal_cortex_dropout_01/config.yaml，继承不改）:
  train_steps=6000, eval_points=200, save_points=500
  optimizer: lr=2e-4, warmup=500, steady_1=500, cosine_anneal=5000, min_lr=5e-5
  model.dropout_p=0.1（继承 config）
  loss: clip_weight=20, temperature=0.15, bottom_k_ratio=0.15, weight_bottom=5.0（继承 config）

单组学预训练超参数（参考 case_renal_cortex_pretrain_pair.yaml，任务规定统一）:
  每模态 lr=1e-3, train_steps=4000, warmup=400, steady_1=0, cosine=3600, min_lr=1e-4
  batch_size=256, vae_beta=1.0, eval_points=200, save_points=4000（仅最终 ckpt）

用法::

    conda activate snapatac
    python scripts/run_hca_renal_cortex_strategy_ablation.py                        # 全量
    python scripts/run_hca_renal_cortex_strategy_ablation.py --strategies scratch   # 单策略
    nohup python -u scripts/run_hca_renal_cortex_strategy_ablation.py > logs/hca_renal_cortex_strategy_ablation.out 2>&1 &

断点续跑: 每个实验幂等——已有完整评估结果/预训练 ckpt 自动跳过。
"""

