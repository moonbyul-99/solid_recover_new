# ============ 工具函数 ============

def log(msg):
    timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    print(f"[{timestamp}] {msg}", flush=True)


def write_yaml(config, filepath):
    """用 PyYAML 写配置文件"""
    filepath = Path(filepath)
    filepath.parent.mkdir(parents=True, exist_ok=True)
    with open(filepath, 'w') as f:
        f.write(f"# Auto-generated by run_ablation.py\n")
        f.write(f"# {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
        yaml.dump(config, f, default_flow_style=False, sort_keys=False, allow_unicode=True)
    log(f"  📝 配置: {filepath}")


def run_cmd(cmd, log_file=None, timeout=None):
    """执行shell命令，返回 exit_code。如果指定 log_file，则输出写入该文件"""
    log(f"  🔧 {cmd[:120]}{'...' if len(cmd) > 120 else ''}")
    if log_file:
        with open(log_file, 'a') as lf:
            lf.write(f"\n[{datetime.datetime.now()}] CMD: {cmd}\n")
            result = subprocess.run(
                cmd, shell=True, cwd=ROOT, executable='/bin/bash',
                stdout=lf, stderr=subprocess.STDOUT,
                timeout=timeout,
            )
    else:
        result = subprocess.run(
            cmd, shell=True, cwd=ROOT, executable='/bin/bash',
            capture_output=True, text=True,
            timeout=timeout,
        )
    ok = result.returncode == 0
    if not ok:
        stderr_info = ''
        if not log_file and result.stderr:
            stderr_info = f' stderr={result.stderr[-200:]}'
        log(f"  ❌ 失败, exit_code={result.returncode}{stderr_info}")
    return ok


def find_actual_output_dir(project_dir_name):
    """查找实际输出目录（可能有时间戳后缀）"""
    actual = OUTPUTS_DIR / project_dir_name
    if actual.exists():
        return actual
    matches = sorted(OUTPUTS_DIR.glob(f"{project_dir_name}*"))
    if matches:
        actual = matches[-1]
        log(f"  📁 找到带时间戳目录: {actual.name}")
        return actual
    return None


def extract_metrics(project_dir_name):
    """从 metrics_summary.json 提取所有指标"""
    actual = find_actual_output_dir(project_dir_name)
    if not actual:
        log(f"  ❌ 输出目录不存在: {project_dir_name}")
        return None
    mp = actual / "eval_result" / "metrics_summary.json"
    if not mp.exists():
        log(f"  ❌ metrics_summary.json 不存在: {mp}")
        return None
    with open(mp) as f:
        return json.load(f)


def find_best(data):
    """找 top_1_hit 最优的 step"""
    top1 = data['metrics']['top_1_hit']
    vals = top1['values']
    best_idx = max(range(len(vals)), key=lambda i: vals[i])
    return {
        'best_step': top1['steps'][best_idx],
        'top_1': vals[best_idx],
        'foscttm': data['metrics']['foscttm']['values'][best_idx],
        'top_5': data['metrics']['top_5_hit']['values'][best_idx],
    }


def compare_tie(t1_a, fos_a, t1_b, fos_b):
    """比较：先看 top_1；差距<0.0005 则 foscttm 低者胜"""
    if abs(t1_a - t1_b) < 0.0005:
        return fos_a < fos_b
    return t1_a > t1_b


def copy_metrics(project_dir_name, phase_dir, exp_name):
    """复制 metrics_summary.json 到 exp-reports"""
    actual = find_actual_output_dir(project_dir_name)
    if not actual:
        return
    src = actual / "eval_result" / "metrics_summary.json"
    dst_dir = EXP_REPORTS_DIR / phase_dir / exp_name
    dst_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst_dir / "metrics_summary.json")
    # 复制 TB 日志（如果有）
    tb_dir = actual / "logs"
    if tb_dir.exists():
        tb_dst = dst_dir / "tb_logs"
        if not tb_dst.exists():
            shutil.copytree(tb_dir, tb_dst)
    log(f"  📋 归档 → {dst_dir}")


def generate_summary_md(phase_name, experiments, best_id, phase_dir):
    """生成阶段汇总 summary.md"""
    lines = [
        f"# {phase_name}",
        "",
        f"生成时间: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        "",
        "## 排名汇总",
        "",
        "| 排名 | 实验 | best_step | top_1 | foscttm | top_5 |",
        "|-----:|------|----------:|------:|--------:|------:|",
    ]
    sorted_exps = sorted(experiments, key=lambda x: x['top_1'], reverse=True)
    for rank, exp in enumerate(sorted_exps, 1):
        marker = " **← 最优**" if exp['id'] == best_id else ""
        lines.append(f"| {rank} | {exp['id']} | {exp['best_step']} | {exp['top_1']:.6f} | {exp['foscttm']:.6f} | {exp['top_5']:.6f} |{marker}")
    
    lines.append("")
    for exp in experiments:
        lines.append(f"## {exp['id']} 逐步轨迹")
        lines.append("")
        lines.append("| step | top_1 | foscttm |")
        lines.append("|-----:|------:|--------:|")
        for i, s in enumerate(exp['steps']):
            b = "**" if s == exp['best_step'] else ""
            lines.append(f"| {b}{s}{b} | {exp['top_1_list'][i]:.6f} | {exp['foscttm_list'][i]:.6f} |")
        lines.append("")
    
    best_exp = next(e for e in experiments if e['id'] == best_id)
    lines.append("## 结论")
    lines.append(f"最优: **{best_id}**, top_1={best_exp['top_1']:.6f}, foscttm={best_exp['foscttm']:.6f}")
    lines.append("")
    
    content = '\n'.join(lines)
    sp = EXP_REPORTS_DIR / phase_dir / "summary.md"
    sp.parent.mkdir(parents=True, exist_ok=True)
    with open(sp, 'w') as f:
        f.write(content)
    log(f"  📊 summary → {sp}")
    return content


def git_commit_push(phase_dir, commit_msg):
    """提交到 exp-reports 分支"""
    log(f"  🔄 Git 提交...")
    
    # 获取当前分支
    r = subprocess.run("git rev-parse --abbrev-ref HEAD", shell=True, cwd=ROOT, capture_output=True, text=True)
    cur = r.stdout.strip()
    
    # stash 未提交更改
    r = subprocess.run("git diff --quiet && git diff --cached --quiet", shell=True, cwd=ROOT)
    stashed = False
    if r.returncode != 0:
        subprocess.run("git stash", shell=True, cwd=ROOT, capture_output=True)
        stashed = True
    
    try:
        subprocess.run("git checkout exp-reports", shell=True, cwd=ROOT, capture_output=True)
        subprocess.run(f"git add exp-reports/{phase_dir}/", shell=True, cwd=ROOT, capture_output=True)
        subprocess.run(f'git commit -m "{commit_msg}"', shell=True, cwd=ROOT, capture_output=True)
        r = subprocess.run("git push origin exp-reports", shell=True, cwd=ROOT, capture_output=True, text=True)
        if r.returncode == 0:
            log(f"  ✅ Push 成功")
        else:
            log(f"  ⚠️ Push: {r.stderr[-200:]}")
    finally:
        subprocess.run(f"git checkout {cur}", shell=True, cwd=ROOT, capture_output=True)
        if stashed:
            subprocess.run("git stash pop", shell=True, cwd=ROOT, capture_output=True)


# ============ 单实验执行 ============

def run_experiment(config_name, project_dir, exp_id, phase_dir):
    """训练→评估→提取指标→归档，返回结果dict或None"""
    log(f"\n{'='*60}")
    log(f"  🧪 {exp_id} | config={config_name} | output={project_dir}")
    log(f"{'='*60}")
    
    config_path = CONFIGS_DIR / f"{config_name}.yaml"
    if not config_path.exists():
        log(f"  ❌ 配置不存在: {config_path}")
        return None
    
    # 检查是否已有评估结果，有则跳过
    existing_data = extract_metrics(project_dir)
    if existing_data is not None:
        best = find_best(existing_data)
        log(f"  ⏭️ 已有结果，跳过训练。best_step={best['best_step']}, top_1={best['top_1']:.6f}")
        copy_metrics(project_dir, phase_dir, exp_id)
        return {
            'id': exp_id,
            'config_name': config_name,
            'project_dir': project_dir,
            'best_step': best['best_step'],
            'top_1': best['top_1'],
            'foscttm': best['foscttm'],
            'top_5': best['top_5'],
            'steps': existing_data['metrics']['top_1_hit']['steps'],
            'top_1_list': existing_data['metrics']['top_1_hit']['values'],
            'foscttm_list': existing_data['metrics']['foscttm']['values'],
        }
    
    retries = 3
    for attempt in range(retries):
        log(f"  [训练] 尝试 {attempt+1}/{retries}...")
        t0 = time.time()
        cmd = f"source {CONDA_SH} && conda activate snapatac && bash scripts/train.sh {config_path} cuda"
        ok = run_cmd(cmd, log_file=LOGS_DIR / f"ablation_train_{config_name}.out")
        t1 = time.time()
        if ok:
            log(f"  ✅ 训练完成 ({t1-t0:.0f}s)")
            break
        log(f"  ⚠️ 训练失败，{'' if attempt == retries-1 else '重试中...'}")
        if attempt == retries - 1:
            log(f"  ❌ 训练失败，跳过此实验")
            return None
    
    # 查找实际输出目录
    actual_dir = find_actual_output_dir(project_dir)
    if not actual_dir:
        log(f"  ❌ 找不到输出目录")
        return None
    actual_name = actual_dir.name
    
    # 评估
    log(f"  [评估] ...")
    cmd = f"source {CONDA_SH} && conda activate snapatac && bash scripts/eval.sh {actual_dir} cuda"
    ok = run_cmd(cmd, log_file=LOGS_DIR / f"ablation_eval_{config_name}.out")
    if not ok:
        log(f"  ❌ 评估失败")
        return None
    log(f"  ✅ 评估完成")
    
    # 提取指标
    data = extract_metrics(actual_name)
    if data is None:
        return None
    
    best = find_best(data)
    result = {
        'id': exp_id,
        'config_name': config_name,
        'project_dir': project_dir,
        'best_step': best['best_step'],
        'top_1': best['top_1'],
        'foscttm': best['foscttm'],
        'top_5': best['top_5'],
        'steps': data['metrics']['top_1_hit']['steps'],
        'top_1_list': data['metrics']['top_1_hit']['values'],
        'foscttm_list': data['metrics']['foscttm']['values'],
    }
    
    log(f"  📊 best_step={best['best_step']}, top_1={best['top_1']:.6f}, foscttm={best['foscttm']:.6f}")
    
    # 归档
    copy_metrics(actual_name, phase_dir, exp_id)
    
    return result


def find_best_experiment(results):
    """从结果列表中找最优（top_1优先，ties用foscttm）"""
    best = max(results, key=lambda x: x['top_1'])
    for r in results:
        if r['id'] != best['id']:
            if not compare_tie(best['top_1'], best['foscttm'], r['top_1'], r['foscttm']):
                best = r
    return best


