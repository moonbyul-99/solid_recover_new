def _build_best_config():
    """构建包含当前所有最优参数的配置"""
    cfg = copy.deepcopy(base_config())
    for attr, loss_key in [
        ('best_temperature', 'temperature'),
        ('best_bottom_k_ratio', 'bottom_k_ratio'),
        ('best_weight_top', 'weight_top'),
        ('best_weight_bottom', 'weight_bottom'),
    ]:
        val = getattr(state, attr)
        if val is not None:
            cfg['loss'][loss_key] = val
    if state.best_embed_dim is not None:
        cfg['model']['embed_dim'] = state.best_embed_dim
    if state.best_hidden_params is not None:
        cfg['model']['hidden_params_1'] = state.best_hidden_params
        cfg['model']['hidden_params_2'] = state.best_hidden_params
    if state.best_clip_weight is not None:
        cfg['loss']['clip_weight'] = state.best_clip_weight
    return cfg


